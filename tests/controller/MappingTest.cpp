int main()
{
    juce::ScopedJuceInitialiser_GUI juceInitialiser;

    std::cout << "ihub-mapping-test\n"
              << "  block: " << kBlockSize << ", sample rate: " << kSampleRate
              << ", hot-reload budget: " << kHotReloadBudgetMs << " ms" << std::endl;

    //==========================================================================
    // 1. The shipped document and schema
    //==========================================================================
    {
        Controller::SetMapping shipped;
        Controller::MappingError error;

        const bool loaded = Controller::loadSetMappingFile (IHUB_SET_YAML, shipped, error);

        check (loaded, std::string ("shared/set.yaml loads")
                           + (loaded ? std::string()
                                     : " (" + error.message + ":" + std::to_string (error.line) + ")"));

        if (loaded)
        {
            check (shipped.schemaVersion == 1, "set.yaml declares schemaVersion 1");
            check (! shipped.name.empty(), "set.yaml has a set name");
            check (shipped.families.size() >= 5,
                   "set.yaml declares at least five families (got "
                       + std::to_string (shipped.families.size()) + ")");
            check (shipped.macros.size() == 8,
                   "set.yaml declares eight macros (got "
                       + std::to_string (shipped.macros.size()) + ")");
            check (shipped.countPads() >= 8,
                   "set.yaml binds at least eight pads (got "
                       + std::to_string (shipped.countPads()) + ")");
            check (shipped.countEncoders() == 8,
                   "set.yaml binds all eight encoders (got "
                       + std::to_string (shipped.countEncoders()) + ")");

            const auto* padZero = shipped.padBinding (0);
            check (padZero != nullptr && padZero->family == "keys"
                       && padZero->instrument == "piano" && padZero->slot == 0,
                   "pad 0 resolves to keys/piano on slot 0");

            const auto* encoderZero = shipped.encoderBinding (0);
            const auto* cutoff = encoderZero != nullptr ? shipped.macroFor (*encoderZero) : nullptr;

            check (cutoff != nullptr && cutoff->id == "cutoff"
                       && cutoff->parameter == "filter.cutoff",
                   "encoder 0 resolves to the cutoff macro");

            bool allSlotsValid = true;

            for (const auto* instrument : shipped.allInstruments())
                if (instrument->slot < 0 || instrument->slot > Controller::SetMapping::maximumSlot)
                    allSlotsValid = false;

            check (allSlotsValid, "every instrument declares a valid slot");
        }

        std::ifstream schemaFile (IHUB_SET_SCHEMA);
        std::string schemaText ((std::istreambuf_iterator<char> (schemaFile)),
                                std::istreambuf_iterator<char>());

        check (! schemaText.empty() && schemaText.find ("\"schemaVersion\"") != std::string::npos,
               "shared/schema/set.schema.json exists and describes schemaVersion");
    }

    //==========================================================================
    // 2. Validation
    //==========================================================================
    {
        Controller::SetMapping parsed;
        Controller::MappingError error;

        check (Controller::parseSetMappingYaml (makeSetYaml ("sine-a"), parsed, error),
               "the generated two-instrument document parses");

        const auto* pad = parsed.padBinding (0);
        check (pad != nullptr && pad->slot == 0 && pad->instrument == "sine-a",
               "generated document resolves pad 0 to sine-a / slot 0");

        Controller::SetMapping emptyBindings;

        check (Controller::parseSetMappingYaml (R"(schemaVersion: 1
families:
  keys:
    name: Keys
    instruments:
      - id: piano
        name: Piano
        slot: 0
macros: {}
pads: []
encoders: []
)", emptyBindings, error),
               "a document with empty pads/encoders and macros parses");

        check (emptyBindings.countPads() == 0 && emptyBindings.countEncoders() == 0,
               "the empty bindings document binds nothing");
    }

    auto expectInvalid = [] (const std::string& label,
                             const std::string& yaml,
                             const std::string& expectedFragment)
    {
        Controller::SetMapping mapping;
        mapping.name = "keep me";

        Controller::MappingError error;
        const bool ok = Controller::parseSetMappingYaml (yaml, mapping, error);

        check (! ok, label + " is rejected");
        check (! ok && error.message.find (expectedFragment) != std::string::npos,
               label + " reports '" + expectedFragment + "' (got '"
                   + error.message + "' at line " + std::to_string (error.line) + ")");
        check (mapping.name == "keep me",
               label + " leaves the previous document untouched");
    };

    auto futureSchemaYaml = makeSetYaml ("sine-a");
    const auto schemaPosition = futureSchemaYaml.find ("schemaVersion: 1");

    if (schemaPosition != std::string::npos)
        futureSchemaYaml.replace (schemaPosition, std::string ("schemaVersion: 1").size(),
                                  "schemaVersion: 2");

    expectInvalid ("a future schemaVersion", futureSchemaYaml, "unsupported schemaVersion");

    expectInvalid ("an unknown family", R"(schemaVersion: 1
families:
  keys:
    name: Keys
    instruments:
      - id: piano
        name: Piano
        slot: 0
macros:
  cutoff:
    name: Cutoff
    parameter: filter.cutoff
pads:
  - pad: 0
    family: drums
    instrument: piano
encoders: []
)", "unknown family");

    expectInvalid ("an unknown instrument", R"(schemaVersion: 1
families:
  keys:
    name: Keys
    instruments:
      - id: piano
        name: Piano
        slot: 0
macros:
  cutoff:
    name: Cutoff
    parameter: filter.cutoff
pads:
  - pad: 0
    family: keys
    instrument: strings
encoders: []
)", "unknown instrument");

    expectInvalid ("a duplicate pad", R"(schemaVersion: 1
families:
  keys:
    name: Keys
    instruments:
      - id: piano
        name: Piano
        slot: 0
macros:
  cutoff:
    name: Cutoff
    parameter: filter.cutoff
pads:
  - pad: 0
    family: keys
    instrument: piano
  - pad: 0
    family: keys
    instrument: piano
encoders: []
)", "duplicate pad");

    expectInvalid ("a duplicate family key", R"(schemaVersion: 1
families:
  keys:
    name: Keys
    instruments:
      - id: piano
        name: Piano
        slot: 0
  keys:
    name: Keys Again
    instruments:
      - id: organ
        name: Organ
        slot: 1
macros:
  cutoff:
    name: Cutoff
    parameter: filter.cutoff
pads: []
encoders: []
)", "duplicate key");

    expectInvalid ("a macro with an inverted range", R"(schemaVersion: 1
families:
  keys:
    name: Keys
    instruments:
      - id: piano
        name: Piano
        slot: 0
macros:
  cutoff:
    name: Cutoff
    parameter: filter.cutoff
    min: 1.0
    max: 0.0
pads: []
encoders: []
)", "min < max");

    expectInvalid ("tab indentation", "schemaVersion: 1\nfamilies:\n\tkeys:\n\t\tname: Keys\n",
                   "tab indentation");

    expectInvalid ("inconsistent indentation", R"(schemaVersion: 1
families:
  keys:
      name: Keys
    instruments:
      - id: piano
        name: Piano
        slot: 0
macros: {}
pads: []
encoders: []
)", "unexpected indentation");

    expectInvalid ("a missing pads section", R"(schemaVersion: 1
families:
  keys:
    name: Keys
    instruments:
      - id: piano
        name: Piano
        slot: 0
macros: {}
encoders: []
)", "pads is required");

    expectInvalid ("a missing encoders section", R"(schemaVersion: 1
families:
  keys:
    name: Keys
    instruments:
      - id: piano
        name: Piano
        slot: 0
macros: {}
pads: []
)", "encoders is required");

    expectInvalid ("an empty families mapping", R"(schemaVersion: 1
families: {}
macros: {}
pads: []
encoders: []
)", "families must not be empty");

    expectInvalid ("a non-finite macro range", R"(schemaVersion: 1
families:
  keys:
    name: Keys
    instruments:
      - id: piano
        name: Piano
        slot: 0
macros:
  cutoff:
    name: Cutoff
    parameter: filter.cutoff
    min: 0.0
    max: nan
pads: []
encoders: []
)", "finite number");

    //==========================================================================
    // 3. Hot reload while audio runs
    //==========================================================================
    const auto setFile = std::filesystem::current_path() / "mapping-hot-reload.yaml";
    writeFileAtomic (setFile, makeSetYaml ("sine-a"));

    std::unique_ptr<SineSource> sourceA = std::make_unique<SineSource> (220.0, 0.2, 0.0);
    std::unique_ptr<SineSource> sourceB = std::make_unique<SineSource> (330.0, 0.2, 1.1);

    AudioEngine::Slot slot0 (0);
    AudioEngine::Slot slot1 (1);
    slot0.setSource (sourceA.get());
    slot1.setSource (sourceB.get());

    AudioEngine::SlotSwitcher switcher (kFadeMilliseconds);
    switcher.setSlots ({ &slot0, &slot1 });
    switcher.prepare (kSampleRate, kBlockSize, kNumChannels);

    Controller::Mapping mapping;

    std::atomic<bool> routedToNewSlot { false };
    std::atomic<double> routedAtMs { 0.0 };
    std::atomic<int> lastArmedSlot { -99 };
    std::atomic<int> hotReloadCount { 0 };
    std::atomic<int> errorCount { 0 };

    Controller::Mapping::Listeners listeners;

    listeners.armSlot = [&] (int targetSlot)
    {
        if (targetSlot >= 0)
            switcher.armSlot (targetSlot);
        else
            switcher.disarm();

        lastArmedSlot.store (targetSlot, std::memory_order_release);

        if (targetSlot == 1 && ! routedToNewSlot.exchange (true))
            routedAtMs.store (nowMs(), std::memory_order_release);
    };

    listeners.changed = [&] (const std::shared_ptr<const Controller::SetMapping>& document,
                             bool hotReload)
    {
        if (hotReload && document != nullptr)
            hotReloadCount.fetch_add (1);
    };

    listeners.error = [&] (const Controller::MappingError&)
    {
        errorCount.fetch_add (1);
    };

    mapping.setListeners (listeners);

    Controller::MappingError loadError;
    check (mapping.load (setFile, &loadError),
           "initial mapping loads" + (loadError.isEmpty()
                                          ? std::string()
                                          : " (" + loadError.message + ")"));
    check (mapping.getRevision() == 1, "initial load publishes revision 1");
    check (mapping.startWatching (20), "the file watcher starts");
    check (mapping.isWatching(), "isWatching() reports the watcher");

    check (mapping.handlePad (0, true), "pad 0 press is mapped");
    check (switcher.getArmedSlot() == 0, "pad 0 arms slot 0");
    check (mapping.getArmedSlot() == 0, "mapping reports slot 0 as armed");
    check (mapping.getActivePad() == 0, "mapping tracks pad 0 as the active pad");

    juce::MidiBuffer midi;
    RenderStats stats;
    float previousSample = 0.0f;

    // Let the 3 ms fade finish before dropout statistics start.
    for (int block = 0; block < kPreRollBlocks; ++block)
        renderBlock (switcher, midi, stats, previousSample);

    stats = RenderStats {};
    previousSample = switcher.getOutputBuffer().getSample (0, kBlockSize - 1);

    check (switcher.getSlotGain (0) > 0.99f, "slot 0 is fully active before the edit");

    // ---- edit set.yaml: pad 0 now points at sine-b (slot 1) ---------------
    const double editIssuedAtMs = nowMs();
    writeFileAtomic (setFile, makeSetYaml ("sine-b", "reverb"));

    const auto renderStart = std::chrono::steady_clock::now();
    const auto blockDuration = std::chrono::microseconds (2600);
    long long blocksRendered = 0;

    const auto renderAndPace = [&]
    {
        renderBlock (switcher, midi, stats, previousSample);
        ++blocksRendered;
        std::this_thread::sleep_until (renderStart + blockDuration * blocksRendered);
    };

    const auto deadline = std::chrono::steady_clock::now()
                          + std::chrono::milliseconds (1200);

    while (std::chrono::steady_clock::now() < deadline)
    {
        renderAndPace();

        // Give the 3 ms crossfade time to settle once the new slot is armed.
        if (routedToNewSlot.load() && blocksRendered > 20)
            break;
    }

    const double reloadLatencyMs = routedAtMs.load() - editIssuedAtMs;

    check (routedToNewSlot.load(), "editing pad 0's instrument arms slot 1");
    check (reloadLatencyMs >= 0.0 && reloadLatencyMs < kHotReloadBudgetMs,
           "routing changed in " + std::to_string (reloadLatencyMs)
               + " ms (budget " + std::to_string (kHotReloadBudgetMs) + " ms)");
    check (switcher.getArmedSlot() == 1, "SlotSwitcher is armed on slot 1");
    check (mapping.getArmedSlot() == 1, "mapping reports slot 1 as armed");
    check (mapping.getRevision() == 2, "the reload published revision 2");
    check (hotReloadCount.load() == 1, "one hot reload was published");
    check (lastArmedSlot.load() == 1, "the arm listener received slot 1");

    check (switcher.getSlotGain (1) > 0.99f, "slot 1 reached full gain");
    check (switcher.getSlotGain (0) < 0.01f, "slot 0 faded out");
    check (stats.alwaysRendered, "every block rendered audio during the reload");
    check (stats.silentBlocks == 0,
           "no dropout: every block stayed above " + std::to_string (kDropoutRmsFloor)
               + " RMS (minimum " + std::to_string (stats.minRms) + ")");
    check (stats.maxDelta <= kDeltaThreshold,
           "no click: max sample delta " + std::to_string (stats.maxDelta)
               + " <= " + std::to_string (kDeltaThreshold));

    // The snapshot itself must describe the new binding.
    if (const auto document = mapping.getMapping())
    {
        const auto* binding = document->padBinding (0);
        check (binding != nullptr && binding->instrument == "sine-b" && binding->slot == 1,
               "the published snapshot binds pad 0 to sine-b / slot 1");
    }
    else
    {
        check (false, "getMapping() returns the published snapshot");
    }

    // Encoder routing follows the reloaded document and the active slot.
    std::optional<Controller::Mapping::MacroChange> lastMacro;
    listeners.macroEvent = [&] (const Controller::Mapping::MacroChange& change)
    {
        lastMacro = change;
    };
    mapping.setListeners (listeners);
    check (mapping.handleEncoder (0, 127), "encoder 0 resolves after the reload");
    check (lastMacro.has_value() && lastMacro->macro.id == "reverb"
               && lastMacro->slot == 1 && std::abs (lastMacro->normalized - 1.0f) < 1.0e-6f
               && std::abs (lastMacro->value - 1.0f) < 1.0e-6f,
           "encoder 0 now drives reverb on slot 1 at full scale");

    // ---- malformed edit keeps the previous routing live -------------------
    const auto revisionBeforeBadEdit = mapping.getRevision();
    const int errorsBeforeBadEdit = errorCount.load();

    writeFileAtomic (setFile, "schemaVersion: 99\nfamilies: []\n");

    const auto badDeadline = std::chrono::steady_clock::now()
                             + std::chrono::milliseconds (600);

    while (std::chrono::steady_clock::now() < badDeadline
           && errorCount.load() == errorsBeforeBadEdit)
    {
        renderAndPace();
    }

    check (errorCount.load() > errorsBeforeBadEdit, "a malformed edit reports an error");
    check (mapping.getRevision() == revisionBeforeBadEdit,
           "a malformed edit does not publish a new document");
    check (mapping.getArmedSlot() == 1, "a malformed edit keeps slot 1 armed");
    check (stats.alwaysRendered && stats.silentBlocks == 0,
           "audio kept flowing across the malformed edit");

    if (const auto document = mapping.getMapping())
    {
        const auto* binding = document->padBinding (0);
        check (binding != nullptr && binding->instrument == "sine-b",
               "the previous pad binding is still live");
    }

    // ---- recovery: a valid edit is applied again --------------------------
    const auto revisionBeforeRecovery = mapping.getRevision();
    writeFileAtomic (setFile, makeSetYaml ("sine-a"));

    const auto recoveryDeadline = std::chrono::steady_clock::now()
                                  + std::chrono::milliseconds (600);

    while (std::chrono::steady_clock::now() < recoveryDeadline
           && mapping.getRevision() == revisionBeforeRecovery)
    {
        renderAndPace();
    }

    check (mapping.getRevision() == revisionBeforeRecovery + 1,
           "a valid edit after an error is published");
    check (mapping.getArmedSlot() == 0, "recovery re-arms the edited slot");
    check (mapping.getLastError().isEmpty(), "the error is cleared after recovery");

    mapping.stopWatching();
    check (! mapping.isWatching(), "stopWatching() stops the watcher");

    std::error_code ec;
    std::filesystem::remove (setFile, ec);

    std::cout << (failures == 0 ? "\nPASS" : "\nFAIL") << ": " << failures
              << " failed check(s)" << std::endl;

    return failures == 0 ? 0 : 1;
}
