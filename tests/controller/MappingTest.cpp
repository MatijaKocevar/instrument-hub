// ihub-mapping-test: the T043 acceptance check.
//
// It covers three things:
//
//   1. The YAML reader: families, instruments, pads, encoders and macros are
//      decoded from the same document that shared/set.yaml uses, and malformed
//      documents are rejected with a line number.
//   2. The shipped shared/set.yaml loads against the shipped schema.
//   3. Hot reload while audio runs. Pad 0 starts on slot 0; set.yaml is edited
//      to point it at slot 1. The Mapping watcher must publish the new document
//      and arm slot 1 within 500 ms, while every rendered block keeps audio
//      flowing and stays free of sample-to-sample steps (the SlotSwitcher
//      crossfade, not a restart).
//
// A malformed edit must leave the previous routing live and must not stop the
// audio stream.

