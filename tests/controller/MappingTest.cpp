constexpr double kSampleRate = 48000.0;
constexpr int kBlockSize = 128;
constexpr int kNumChannels = 2;
constexpr float kFadeMilliseconds = 3.0f;
constexpr int kPreRollBlocks = 60;
constexpr double kHotReloadBudgetMs = 500.0;
constexpr double kDropoutRmsFloor = 0.05;
constexpr double kDeltaThreshold = 0.05;

int failures = 0;

void check (bool condition, const std::string& what)
{
    std::cout << (condition ? "ok  : " : "FAIL: ") << what << std::endl;

    if (! condition)
        ++failures;
}

double nowMs()
{
    using Clock = std::chrono::steady_clock;
    return std::chrono::duration<double, std::milli> (Clock::now().time_since_epoch()).count();
}

void writeFileAtomic (const std::filesystem::path& path, const std::string& contents)
{
    const auto temporary = std::filesystem::path (path.string() + ".tmp");

    {
        std::ofstream stream (temporary, std::ios::binary | std::ios::trunc);

        if (! stream)
            throw std::runtime_error ("cannot write " + temporary.string());

        stream << contents;
        stream.flush();
    }

    std::error_code ec;
    std::filesystem::rename (temporary, path, ec);

    if (ec)
    {
        std::filesystem::remove (path, ec);
        std::filesystem::rename (temporary, path, ec);
    }

    if (ec)
        throw std::runtime_error ("cannot replace " + path.string() + ": " + ec.message());
}

std::string makeSetYaml (const std::string& padInstrument,
                         const std::string& encoderMacro = "cutoff")
{
    return R"(# generated by ihub-mapping-test
schemaVersion: 1
name: Hot Reload Test

families:
  keys:
    name: Keys
    instruments:
      - id: sine-a
        name: Sine A
        slot: 0
      - id: sine-b
        name: Sine B
        slot: 1

macros:
  cutoff:
    name: Cutoff
    parameter: filter.cutoff
    min: 0.0
    max: 1.0
    default: 0.5
  reverb:
    name: Reverb
    parameter: reverb.mix
    min: 0.0
    max: 1.0
    default: 0.25

pads:
  - pad: 0
    family: keys
    instrument: )" + padInstrument + R"(

encoders:
  - encoder: 0
    macro: )" + encoderMacro + "\n";
}

