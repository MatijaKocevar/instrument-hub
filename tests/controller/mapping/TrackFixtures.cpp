std::string makeTrackHeader()
{
    std::ostringstream yaml;

    yaml << "# generated by ihub-mapping-test\n"
         << "schemaVersion: 2\n"
         << "layout: tracks\n"
         << "name: Track Layout Test\n"
         << "\n"
         << "tracks:\n";

    for (int slot = 0; slot < 8; ++slot)
    {
        yaml << "  - id: track-" << slot + 1 << "\n"
             << "    name: Track " << slot + 1 << "\n"
             << "    slot: " << slot << "\n";

        if (slot == 0)
            yaml << "    hotFx:\n"
                 << "      - eq\n"
                 << "      - comp\n";
        else if (slot == 7)
            yaml << "    hotFx:\n"
                 << "      - delay\n";
    }

    return yaml.str();
}

std::string makeTrackPads()
{
    std::ostringstream yaml;
    yaml << "\npads:\n";

    for (int column = 0; column < 8; ++column)
        yaml << "  - pad: " << 56 + column << "\n"
             << "    role: track\n"
             << "    track: track-" << column + 1 << "\n";

    for (int column = 0; column < 8; ++column)
        yaml << "  - pad: " << 48 + column << "\n"
             << "    role: fx\n"
             << "    track: track-" << column + 1 << "\n"
             << "    hot: 0\n";

    for (int column = 0; column < 8; ++column)
        yaml << "  - pad: " << 40 + column << "\n"
             << "    role: fx\n"
             << "    track: track-" << column + 1 << "\n"
             << "    hot: 1\n";

    for (int step = 0; step <= 4; ++step)
        for (int column = 0; column < 8; ++column)
            yaml << "  - pad: " << step * 8 + column << "\n"
                 << "    role: volume\n"
                 << "    track: track-" << column + 1 << "\n"
                 << "    step: " << step << "\n";

    return yaml.str();
}

std::string makeTracksYaml (bool includeEmptySections)
{
    auto yaml = makeTrackHeader() + makeTrackPads();

    if (includeEmptySections)
        yaml += "\nfamilies: {}\nmacros: {}\nencoders: []\n";

    return yaml;
}

std::string replaceOnce (std::string text, const std::string& from, const std::string& to)
{
    const auto position = text.find (from);

    if (position != std::string::npos)
        text.replace (position, from.size(), to);

    return text;
}

int lineOfOccurrence (const std::string& text, const std::string& needle, int occurrence)
{
    std::size_t position = 0;

    for (int found = 0; found < occurrence; ++found)
    {
        position = text.find (needle, position);

        if (position == std::string::npos)
            return 0;

        if (found + 1 < occurrence)
            position += needle.size();
    }

    const auto offset = static_cast<std::string::difference_type> (position);
    return 1 + static_cast<int> (std::count (text.begin(), text.begin() + offset, '\n'));
}

int lineOf (const std::string& text, const std::string& needle)
{
    return lineOfOccurrence (text, needle, 1);
}

