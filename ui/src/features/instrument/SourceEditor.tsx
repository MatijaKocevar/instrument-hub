import type { ReactElement } from "react";

import type { ControlPatch } from "../../api/client";
import { isPluginSource } from "./source";

interface SourceEditorProps {
  readonly patch: ControlPatch;
  readonly editorOpen?: boolean;
  readonly editorBusy?: boolean;
  readonly onOpenEditor?: (slot: number) => void;
  readonly onReload?: () => void;
  readonly reloadBusy?: boolean;
}

export function SourceEditor({
  patch,
  editorOpen,
  editorBusy,
  onOpenEditor,
  onReload,
  reloadBusy,
}: SourceEditorProps): ReactElement {
  const isPlugin = isPluginSource(patch);
  const editor = editorOpen === true || patch.editorOpen === true;
  const hasError = patch.error !== undefined && patch.error.length > 0;

  return (
    <div
      className="instrument__editor"
      data-testid="source-editor"
      data-kind={patch.instrument.kind}
      data-open={editor ? "true" : "false"}
      data-slot={patch.slot}
      data-error={hasError ? "true" : "false"}
    >
      <div className="instrument__editor-actions">
        <button
          className="instrument__button"
          type="button"
          data-testid="source-open-editor"
          data-slot={patch.slot}
          data-busy={editorBusy === true ? "true" : "false"}
          disabled={
            !isPlugin || editorBusy === true || onOpenEditor === undefined
          }
          onClick={() => {
            onOpenEditor?.(patch.slot);
          }}
        >
          Open editor
        </button>
        {isPlugin ? (
          <button
            className="instrument__button instrument__button--small"
            type="button"
            data-testid="source-reload"
            data-busy={reloadBusy === true ? "true" : "false"}
            disabled={reloadBusy === true || onReload === undefined}
            onClick={() => {
              onReload?.();
            }}
          >
            Reload plugin
          </button>
        ) : null}
      </div>

      <p className="instrument__field-hint" data-testid="source-editor-hint">
        {isPlugin
          ? "Opens the plug-in's native window on the engine desktop. Close that window to close the editor. Reload rebuilds the plug-in instance if it stops responding."
          : "This source is generated by the engine; there are no plug-in parameters to edit."}
      </p>
    </div>
  );
}
